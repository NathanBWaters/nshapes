const recipe = ([id, name, icon, [a, b], activeText, flavor, rules, modifiers]: Row): EvolutionRecipe => ({
  id,
  name,
  icon,
  families: [[W[a]], [W[b]]],
  familyText: `${NAME[a]} + ${NAME[b]}`,
  activeText,
  flavor,
  source: { rules, ...(modifiers ? { modifiers } : {}) },
});

