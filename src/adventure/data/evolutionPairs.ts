/**
 * Pair evolutions: two specific weapons fused into a 20-second power state.
 *
 * The 9 signature recipes in evolutions.ts arm from weapon FAMILIES and are
 * taught by star rewards. These arm from one exact pair and are DISCOVERED:
 * hold both weapons, match a Catalyst, and the recipe joins the Recipe Guide.
 * Together there are 4 evolutions per Armory weapon (each weapon sits in
 * about 8 recipes).
 *
 * Design rules (keep these true when adding one):
 *  - Each recipe has its own twist, not "A also does B". It turns one weapon's
 *    output into a new kind of payoff, adds a finale, cashes a resource in,
 *    rewrites a rule (free mistakes, simplified board), or scales off the fight.
 *  - Every recipe helps the fight (damage, survival or tempo), even the coin ones.
 *  - No pair arms two recipes, and no pair duplicates a signature recipe's
 *    families (__tests__/adventureEvolutions.test.ts checks both).
 *  - `activeText` is exact and short; numbers in it match the rules.
 */
