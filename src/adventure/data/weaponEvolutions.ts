// ─── Lookup Tables & Clean Helper Exports ───────────────────────────────────

export const WEAPON_EVOLUTION_MAP: ReadonlyMap<string, WeaponEvolutionDef> = new Map(
  WEAPON_EVOLUTIONS.map(e => [e.id, e]),
);

const EVOLUTIONS_BY_WEAPON: ReadonlyMap<string, readonly WeaponEvolutionDef[]> = (() => {
  const map = new Map<string, WeaponEvolutionDef[]>();
  for (const e of WEAPON_EVOLUTIONS) {
    const list = map.get(e.weaponId) ?? [];
    list.push(e);
    map.set(e.weaponId, list);
  }
  for (const list of map.values()) {
    list.sort((a, b) => a.slotIndex - b.slotIndex);
  }
  return map;
})();

/** Total count of authored per-weapon evolutions (192). */
export const EVOLUTION_COUNT = WEAPON_EVOLUTIONS.length;

/** Total count of Armory weapons with authored evolutions (64). */
export const EVOLUTION_WEAPON_COUNT = EVOLUTIONS_BY_WEAPON.size;

/** Return the 3 evolutions (`slotIndex: 0 | 1 | 2`) for an Armory weapon, in slot order. */
export const evolutionsForWeapon = (weaponId: string): readonly WeaponEvolutionDef[] =>
  EVOLUTIONS_BY_WEAPON.get(weaponId) ?? [];

/** Return the default Slot A (`slotIndex: 0`) evolution for an Armory weapon. */
export const defaultEvolutionForWeapon = (weaponId: string): WeaponEvolutionDef | undefined =>
  EVOLUTIONS_BY_WEAPON.get(weaponId)?.[0];

/** Look up a single evolution definition by ID (or undefined if not found). */
export const getWeaponEvolution = (evoId: string): WeaponEvolutionDef | undefined =>
  WEAPON_EVOLUTION_MAP.get(evoId);

/** True when `id` is one of the 192 canonical per-weapon evolution IDs. */
export const isWeaponEvolutionId = (id: string): boolean => WEAPON_EVOLUTION_MAP.has(id);

/** Ultra-concise HUD verb (<= 58 chars) with safe fallback to `tagline`. */
export const evolutionShortVerb = (def: WeaponEvolutionDef): string => def.shortVerb ?? def.tagline;

/** Player-facing CVD-safe trigger description for `def`. */
export const evolutionConditionText = (def: WeaponEvolutionDef, colorblind = false): string => {
  if (def.condition.kind === 'color_set' || def.condition.kind === 'trait_cycle') {
    return formatEvolutionConditionText(def.condition, colorblind);
  }
  return def.conditionText;
};

/** Compact CVD-safe HUD condition badge for `def` (<= 22 chars). */
export const evolutionConditionShort = (def: WeaponEvolutionDef, colorblind = false): string => {
  if (def.condition.kind === 'color_set' || (def.condition.kind === 'trait_cycle' && def.condition.attr === 'color')) {
    return formatEvolutionConditionShort(def.condition, colorblind);
  }
  return def.conditionShort ?? def.conditionText;
};
