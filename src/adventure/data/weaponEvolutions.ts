// ─── Dynamic CVD-safe Condition Formatting Helpers ──────────────────────────

const cap = (s: string): string => (s ? s[0].toUpperCase() + s.slice(1) : s);

const colorText = (color: Color, colorblind: boolean): string => {
  const name = cap(cardColorLabel(color, colorblind));
  return colorblind ? `${name} (${cardColorCode(color, true)})` : name;
};

const shapePlural = (shape: Shape): string => formatShapeName(shape, true);

/**
 * Format any `EvolutionCondition` into plain-English copy using the universal
 * CVD-safe palette (Orange (O) / Blue (B) / Pink (P), Circles / Triangles / Bolts).
 */
export const formatEvolutionConditionText = (cond: EvolutionCondition, colorblind = false): string => {
  switch (cond.kind) {
    case 'color_set': {
      const label = cond.color === 'any_same' ? 'single-color' : colorText(cond.color, colorblind);
      return cond.consecutive
        ? `Hit ${cond.target} ${label} Sets in a row`
        : `Match ${cond.target} all-${label} Sets`;
    }
    case 'shape_set': {
      const label = cond.shape === 'any_same' ? 'all-same-shape' : `all-${formatShapeName(cond.shape)}`;
      return cond.consecutive
        ? `Hit ${cond.target} consecutive ${label} Sets`
        : `Match ${cond.target} ${label} Sets`;
    }
    case 'number_set':
      if (cond.mode === 'diff') {
        return cond.consecutive
          ? `Hit ${cond.target} consecutive 1-2-3 (all-different number) Sets`
          : `Match ${cond.target} 1-2-3 (all-different number) Sets`;
      }
      return cond.consecutive
        ? `Hit ${cond.target} consecutive same-number Sets`
        : `Match ${cond.target} same-number Sets (all 1s, 2s, or 3s)`;
    case 'exact_diff_traits': {
      if (cond.onlyDiffAttr) {
        return cond.consecutive
          ? `Get ${cond.target} consecutive Sets where ONLY the ${cond.onlyDiffAttr} differs`
          : `Get ${cond.target} Sets where ONLY the ${cond.onlyDiffAttr} differs`;
      }
      if (cond.onlySameAttr) {
        return `Score ${cond.target} Sets with ${cond.diffCount} traits different & same ${cond.onlySameAttr}`;
      }
      return cond.consecutive
        ? `Hit ${cond.target} consecutive Sets with exactly ${cond.diffCount} differing trait${cond.diffCount > 1 ? 's' : ''}`
        : `Land ${cond.target} Sets with ${cond.diffCount}${cond.diffCount === 3 ? '+' : ''} differing trait${cond.diffCount > 1 ? 's' : ''}`;
    }
    case 'rainbow_set':
      return cond.consecutive
        ? `Hit ${cond.target} back-to-back all-different (Rainbow) Sets`
        : `Land ${cond.target} Rainbow Sets`;
    case 'purity_step':
      return (cond.minChain ?? 2) >= 3
        ? `Complete ${cond.target === 1 ? 'a' : cond.target} 3-step Escalating Purity chain (1→2→3 diff)`
        : `Trigger ${cond.target} Escalating Purity chains`;
    case 'board_geometry':
      switch (cond.geometry) {
        case 'corners': return `Score ${cond.target} Sets using 2+ board corner cards`;
        case 'same_row': return `Make ${cond.target} same-row Sets`;
        case 'same_col': return `Match ${cond.target} vertical (same-column) Sets`;
        case 'adjacent_cluster': return `Score ${cond.target} Sets whose 3 cards all touch each other`;
        case 'reuse_last_slot': return `Reuse a slot from your last Set ${cond.target} times${cond.consecutive ? ' in a row' : ''}`;
        case 'touch_last_set': return `Make ${cond.target}${cond.consecutive ? ' consecutive' : ''} Sets touching your last Set`;
      }
    case 'trait_cycle':
      if (cond.attr === 'color') {
        return `Match an ${colorText('red', colorblind)}, ${colorText('green', colorblind)}, and ${colorText('purple', colorblind)} Set`;
      }
      if (cond.attr === 'shape') {
        return `Match an all-${formatShapeName('oval')}, all-${formatShapeName('diamond')}, and all-${formatShapeName('squiggle')} Set`;
      }
      return 'Match an all-1s, all-2s, and all-3s Set';
    case 'base_damage_hit':
      return (cond.target ?? 1) > 1
        ? `Hit a Set base damage of ${cond.threshold}+ ${cond.target} times`
        : `Hit a Set base damage of ${cond.threshold}+`;
    case 'total_damage_hit':
      return `Deal ${cond.threshold}+ total damage in a single Set turn`;
    case 'multiplied_hit':
      return `Land ${cond.target ?? 1} Sets with a ≥${cond.threshold}× combined multiplier`;
    case 'cards_destroyed_single_set':
      return `Destroy ${cond.threshold}+ cards in a single Set turn`;
    case 'quick_sets':
      return `Make ${cond.target}${cond.consecutive ? ' consecutive' : ''} quick Sets (<${cond.withinMs / 1000}s apart)`;
    case 'sets_in_window':
      return `Score ${cond.target} Sets within ${cond.windowMs / 1000} seconds`;
    case 'clean_streak':
      return `Hit a ${cond.target}-Set clean streak (zero mistakes)`;
    case 'patient_sets':
      return `Land ${cond.target} deliberate Sets (${cond.minGapMs / 1000}s+ pause each)`;
    case 'combo_reach':
      return `Reach a ${cond.minCombo}× Speed Combo`;
    case 'special_cards_matched':
      return cond.inSingleSet
        ? `Match ${cond.target}+ ${cond.cardTag === 'any_special' ? 'special' : cond.cardTag} cards in a single Set`
        : `Match ${cond.target} ${cond.cardTag === 'any_special' ? 'special' : cond.cardTag} cards`;
    case 'trick_payout':
      return `Trigger ${cond.target} ${cond.trick} payouts`;
    case 'weapon_proc':
      return `Trigger ${cond.target} ${cond.procKind} procs`;
    case 'synergy_delta':
      return `Gain +${cond.target} ${SYNERGY_ATTR_META[cond.attr].label} synergy`;
    case 'board_state':
      return `Score ${cond.setsRequired ?? 1} Sets meeting board state (${cond.check} ${cond.threshold})`;
    case 'parry_feat':
      return cond.mode === 'perfect'
        ? `Land ${cond.target} Perfect Parry${cond.target > 1 ? 's' : ''}`
        : cond.mode === 'staggered_set'
          ? `Score ${cond.target} Sets while a foe is Staggered`
          : `Land ${cond.target} Parries`;
    case 'hazard_feat':
      return `Clear or defuse ${cond.target} ${cond.hazardKind === 'any' ? 'hazards' : cond.hazardKind}`;
    case 'resource_action':
      return `Complete ${cond.target} ${cond.action.replace(/_/g, ' ')}`;
    case 'understudy_mirror':
      return cond.mode === 'ignite_with_left'
        ? 'Ignite automatically whenever your left neighbor weapon evolves'
        : 'Complete your left neighbor weapon’s evolution objective';
  }
};

/** Compact CVD-safe HUD condition badge (<= 22 chars). */
export const formatEvolutionConditionShort = (cond: EvolutionCondition, colorblind = false): string => {
  switch (cond.kind) {
    case 'color_set': {
      const label = cond.color === 'any_same' ? '1-color' : colorText(cond.color, colorblind);
      return cond.consecutive ? `${cond.target} ${label} row` : `${cond.target} ${label} Sets`;
    }
    case 'shape_set': {
      const label = cond.shape === 'any_same' ? 'same-shape' : shapePlural(cond.shape);
      return cond.consecutive ? `${cond.target} ${label} row` : `${cond.target} ${label}`;
    }
    case 'trait_cycle':
      if (cond.attr === 'color') {
        return colorblind ? 'O + B + P Sets' : 'Orange + Blue + Pink';
      }
      if (cond.attr === 'shape') return 'Circle + Tri + Bolt';
      return '1s + 2s + 3s Sets';
    default:
      return '';
  }
};

interface EvoSpec {
  id: string;
  weaponId: string;
  slotIndex: 0 | 1 | 2;
  name: string;
  icon: IconName;
  condition: EvolutionCondition;
  conditionText: string;
  conditionShort: string;
  durationSec: number;
  synergyTags: readonly SynergyAttrId[];
  tagline: string;
  shortVerb: string;
  rules?: Rule[];
  modifiers?: Modifiers;
  openingEffects?: Effect[];
  finaleEffects?: Effect[];
}

const evo = (spec: EvoSpec): WeaponEvolutionDef => ({
  id: spec.id,
  weaponId: spec.weaponId,
  slotIndex: spec.slotIndex,
  name: spec.name,
  tagline: spec.tagline,
  shortVerb: spec.shortVerb,
  icon: spec.icon,
  accent: SYNERGY_ATTR_META[spec.synergyTags[0]].color,
  condition: spec.condition,
  conditionText: spec.conditionText,
  conditionShort: spec.conditionShort,
  durationMs: spec.durationSec * 1000,
  synergyTags: spec.synergyTags,
  source: {
    ...(spec.rules && spec.rules.length > 0 ? { rules: spec.rules } : {}),
    ...(spec.modifiers ? { modifiers: spec.modifiers } : {}),
  },
  ...(spec.openingEffects && spec.openingEffects.length > 0 ? { openingEffects: spec.openingEffects } : {}),
  ...(spec.finaleEffects && spec.finaleEffects.length > 0 ? { finaleEffects: spec.finaleEffects } : {}),
});

